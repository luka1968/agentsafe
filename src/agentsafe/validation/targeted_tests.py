"""Stage 8 — targeted tests: generation + isolated execution + honest records.

Given a candidate finding or invariant, we generate a targeted Foundry test
(unit, property, or invariant-style) in an ISOLATED temp directory, compile
and run it with the project's supported tool (foundry forge when available).

Honesty rules (hard):
- A generated test that was never executed is NOT validation evidence
  (`result="not_executed"`).
- A failed test does not prove the contract is safe (failure may be an
  incorrect harness, wrong pragma, or compile error).
- Execution happens ONLY in isolated local temp dirs; never against live
  third-party contracts and never with real funds.
- Every run records: environment, inputs, prerequisites, expected behavior,
  observed behavior, result, and limitations.
"""

from __future__ import annotations

import json
import logging
import os
import shutil
import subprocess
import tempfile
import textwrap
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

logger = logging.getLogger("agentSAFE.targeted_tests")

FOUNDRY_BIN = os.environ.get("FOUNDRY_BIN") or (
    os.path.expanduser("~/.foundry/bin/forge")
    if os.path.exists(os.path.expanduser("~/.foundry/bin/forge"))
    else "forge"
)


@dataclass
class TestRunRecord:
    """Honest record of one targeted test run. A record is evidence only if it
    actually executed (result in passed/failed/error); not_executed records
    are explicitly never evidence. Failed tests never prove safety."""

    __test__ = False  # dataclass, not a pytest test class
    """What happened when a targeted test was (attempted to be) run."""

    test_id: str
    kind: str                      # unit | property | invariant
    target_function: str = ""
    hypothesis: str = ""           # the claim being tested
    environment: str = ""          # forge version / OS / sandbox dir
    inputs: str = ""               # concrete inputs exercised
    prerequisites: list[str] = field(default_factory=list)
    expected_behavior: str = ""
    observed_behavior: str = ""
    result: str = "not_executed"   # not_executed | passed | failed | error | skipped
    limitations: list[str] = field(default_factory=list)
    stdout_tail: str = ""
    duration_seconds: float | None = None

    def to_dict(self) -> dict[str, Any]:
        return {
            "test_id": self.test_id,
            "kind": self.kind,
            "target_function": self.target_function,
            "hypothesis": self.hypothesis,
            "environment": self.environment,
            "inputs": self.inputs,
            "prerequisites": list(self.prerequisites),
            "expected_behavior": self.expected_behavior,
            "observed_behavior": self.observed_behavior,
            "result": self.result,
            "limitations": list(self.limitations),
            "stdout_tail": self.stdout_tail[:2000],
            "duration_seconds": self.duration_seconds,
        }

    @property
    def is_evidence(self) -> bool:
        """Only EXECUTED tests are evidence; not_executed/error are not."""
        return self.result in ("passed", "failed")


# ---------------------------------------------------------------------------
# generators (pure: source -> test file text)
# ---------------------------------------------------------------------------

def _contract_block(source: str, contract_name: str) -> str:
    """Wrap contract source so the test file compiles standalone."""
    if "pragma solidity" in source:
        head = source.split("contract " + contract_name, 1)[0]
        body = source.split("contract " + contract_name, 1)[1]
        return f"{head}contract {contract_name}{body}"
    return textwrap.dedent(f"""\
        // SPDX-License-Identifier: MIT
        pragma solidity ^0.8.19;

        {source}
    """)


def generate_unit_test(
    finding_title: str,
    source: str,
    contract_name: str,
    target_function: str,
    precondition_lines: list[str],
    assert_lines: list[str],
    test_id: str,
) -> str:
    """Generate a Foundry unit test that calls target_function under the given
    preconditions and asserts the claimed behavior."""
    pre = "\n        ".join(precondition_lines) or "        // no preconditions"
    asserts = "\n        ".join(assert_lines) or "        assertTrue(true); // placeholder"
    return textwrap.dedent(f"""\
        // SPDX-License-Identifier: MIT
        pragma solidity ^0.8.19;
        import "forge-std/Test.sol";

        // Targeted test generated by agentSAFE Stage 8 from the hypothesis:
        //   {finding_title}
        // Run in an isolated sandbox. A FAILED test is evidence the hypothesis
        // was not reproduced; it is NOT proof the contract is safe.

        contract TargetedTest_{test_id.replace('-', '_')} is Test {{
            function test_hypothesis() public {{
        {pre}
        {asserts}
            }}
        }}
        """)


def generate_property_test(
    hypothesis: str,
    source: str,
    contract_name: str,
    property_body: str,
    test_id: str,
    n_runs: int = 128,
) -> str:
    """Generate a Foundry fuzz/property test over bounded random inputs."""
    return textwrap.dedent(f"""\
        // SPDX-License-Identifier: MIT
        pragma solidity ^0.8.19;
        import "forge-std/Test.sol";

        // Property-based test (bounded fuzz) for:
        //   {hypothesis}
        // Bounded: {n_runs} random runs. Passing bounded fuzz is evidence for
        // the tested conditions only, never a proof.

        contract PropertyTest_{test_id.replace('-', '_')} is Test {{
            function test_property(uint256 amount) public {{
                uint256 bounded = amount % 1e24; // keep within sane bounds
                vm.assume(bounded > 0);
        {textwrap.indent(property_body, '        ')}
            }}
        }}
        """)


# ---------------------------------------------------------------------------
# executor (isolated sandbox)
# ---------------------------------------------------------------------------

def _forge_available() -> bool:
    try:
        subprocess.run(
            [FOUNDRY_BIN, "--version"], capture_output=True, timeout=10,
            check=False,
        )
        return True
    except (OSError, subprocess.SubprocessError):
        return False


def run_foundry_test(
    test_source: str,
    contract_source: str,
    contract_name: str,
    *,
    test_id: str,
    hypothesis: str,
    kind: str,
    expected_behavior: str,
    inputs: str = "",
    timeout_seconds: int = 120,
) -> TestRunRecord:
    """Compile + run one generated test in an isolated temp sandbox.

    Always returns a TestRunRecord; `result` distinguishes:
      not_executed - forge unavailable / skipped (NOT evidence)
      error        - sandbox compile/run failure (NOT evidence)
      passed       - executed and assertions held (evidence for tested conds)
      failed       - executed and an assertion broke (evidence of failure)
    Never touches live contracts; never uses real funds.
    """
    rec = TestRunRecord(
        test_id=test_id, kind=kind, hypothesis=hypothesis,
        target_function=contract_name,
        expected_behavior=expected_behavior, inputs=inputs,
    )
    if not _forge_available():
        rec.observed_behavior = "forge not available; test generated but not executed"
        rec.limitations.append(
            "generated test was never executed — it is NOT validation evidence")
        return rec

    sandbox = Path(tempfile.mkdtemp(prefix="agentsafe-test-"))
    try:
        src_dir = sandbox / "src"
        test_dir = sandbox / "test"
        src_dir.mkdir()
        test_dir.mkdir()
        (src_dir / f"{contract_name}.sol").write_text(
            _contract_block(contract_source, contract_name), encoding="utf-8")
        (test_dir / f"Targeted_{test_id}.t.sol").write_text(
            test_source, encoding="utf-8")
        (sandbox / "foundry.toml").write_text(
            "[profile.default]\nsolc = \"0.8.19\"\n"
            "src = \"src\"\ntest = \"test\"\n"
            "out = \"out\"\ncache_path = \"cache\"\n"
            "via_ir = false\noptimizer = true\n",
            encoding="utf-8")
        env = dict(os.environ)
        env["FOUNDRY_ROOT"] = str(sandbox)
        env["PATH"] = os.path.dirname(FOUNDRY_BIN) + os.pathsep + env.get("PATH", "")
        import time
        t0 = time.monotonic()
        try:
            proc = subprocess.run(
                [FOUNDRY_BIN, "test", "--root", str(sandbox),
                 "--match-test", "test_", "-q"],
                capture_output=True, text=True, timeout=timeout_seconds,
                env=env, check=False,
            )
            rec.duration_seconds = round(time.monotonic() - t0, 3)
        except subprocess.TimeoutExpired:
            rec.result = "error"
            rec.observed_behavior = f"forge test timed out after {timeout_seconds}s"
            rec.limitations.append("timeout is a harness/compile failure, not evidence")
            return rec
        out = (proc.stdout or "") + "\n" + (proc.stderr or "")
        rec.stdout_tail = out[-2000:]
        if proc.returncode == 0 and "FAIL" not in out and "failed" not in out:
            rec.result = "passed"
            rec.observed_behavior = (
                "forge test returned 0; assertions held under the tested inputs")
            rec.limitations.append(
                "passing bounded tests covers only tested inputs/conditions; "
                "it is NOT proof the invariant always holds")
        elif proc.returncode != 0 or "FAIL" in out:
            rec.result = "failed"
            rec.observed_behavior = (
                "forge test reported a failure; the hypothesis was NOT "
                "reproduced under the tested conditions")
            rec.limitations.append(
                "a failed test does not prove the contract is safe — the "
                "harness may be wrong; it only shows the tested claim failed "
                "to reproduce")
        else:
            rec.result = "error"
            rec.observed_behavior = "unrecognized forge output"
        return rec
    finally:
        shutil.rmtree(sandbox, ignore_errors=True)


def run_property_test(
    contract_source: str,
    contract_name: str,
    *,
    test_id: str,
    hypothesis: str,
    property_body: str,
    expected_behavior: str,
    inputs: str = "bounded uint256 fuzz",
) -> TestRunRecord:
    return run_foundry_test(
        generate_property_test(hypothesis, contract_source, contract_name,
                               property_body, test_id),
        contract_source, contract_name,
        test_id=test_id, hypothesis=hypothesis, kind="property",
        expected_behavior=expected_behavior, inputs=inputs,
    )


# ---------------------------------------------------------------------------
# convenience: validate a finding/invariant with a targeted test
# ---------------------------------------------------------------------------

def targeted_test_for_invariant(
    invariant: dict[str, Any],
    contract_source: str,
    contract_name: str,
    *,
    property_body: str,
    expected_behavior: str,
) -> TestRunRecord:
    """Stage 8: attempt validation of one candidate invariant via a bounded
    property test in an isolated sandbox. Honest result always."""
    statement = invariant.get("statement", "invariant")
    test_id = "inv_" + (invariant.get("invariant_type", "gen")).replace("_", "")[:24]
    return run_property_test(
        contract_source, contract_name,
        test_id=test_id, hypothesis=statement,
        property_body=property_body, expected_behavior=expected_behavior,
    )
