"""Production fix: task ids must be argv-safe.

A task id generated by `secrets.token_urlsafe` could start with '-'; passing it
to the worker as `--task-id <id>` made argparse treat it as an option and exit 2
(no report produced). Fixed at both ends: the generator never emits a leading
dash, and the workflows pass values with `=`.
"""

from __future__ import annotations

import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[1]


def test_new_task_id_is_argv_safe():
    from agentsafe.task_store import new_task_id

    ids = [new_task_id() for _ in range(500)]
    assert all(tid and tid[0].isalnum() for tid in ids)
    assert not any(tid.startswith("-") for tid in ids)
    assert all(len(tid) >= 20 for tid in ids)  # entropy preserved


def _load_run_audit():
    sys.path.insert(0, str(ROOT / "scripts"))
    sys.path.insert(0, str(ROOT / "src"))
    import run_audit  # noqa: PLC0415

    return run_audit


def test_equals_form_accepts_leading_dash_task_id(monkeypatch):
    run_audit = _load_run_audit()
    monkeypatch.setattr(sys, "argv", [
        "run_audit.py", "--address=0x" + "11" * 20,
        "--task-id=-54Xt9GCGcjdhuEpfMUUeN0M", "--output=/tmp/r.json",
    ])
    ns = run_audit.parse_args()
    assert ns.task_id == "-54Xt9GCGcjdhuEpfMUUeN0M"


def test_space_form_would_break_on_leading_dash(monkeypatch):
    run_audit = _load_run_audit()
    monkeypatch.setattr(sys, "argv", [
        "run_audit.py", "--address", "0x" + "11" * 20,
        "--task-id", "-54Xt9GCGcjdhuEpfMUUeN0M", "--output", "r.json",
    ])
    with pytest.raises(SystemExit) as exc:
        run_audit.parse_args()
    assert exc.value.code == 2  # the exact production failure


def test_workflows_use_equals_form():
    for name in ("docker-audit.yml", "audit.yml"):
        text = (ROOT / ".github" / "workflows" / name).read_text(encoding="utf-8")
        assert '--task-id="$AUDIT_TASK_ID"' in text
        assert '--address="$AUDIT_ADDRESS"' in text
        assert '--task-id "$AUDIT_TASK_ID"' not in text
